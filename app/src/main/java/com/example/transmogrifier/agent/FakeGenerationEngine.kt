package com.example.transmogrifier.agent

import com.example.transmogrifier.project.NoticeKind
import com.example.transmogrifier.project.ProjectId
import com.example.transmogrifier.project.ProjectStore
import com.example.transmogrifier.project.TranscriptEntry
import com.example.transmogrifier.project.WorkspaceResult
import kotlinx.coroutines.CancellationException
import kotlinx.coroutines.NonCancellable
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.FlowCollector
import kotlinx.coroutines.flow.flow
import kotlinx.coroutines.withContext

/** Streams canned text and writes a small demo site, so the UI can be exercised without a provider. */
class FakeGenerationEngine(private val store: ProjectStore, private val delayMillis: Long = 40) :
    GenerationEngine {
    override fun generate(
        projectId: ProjectId,
        prompt: String?,
        fixErrors: Boolean
    ): Flow<GenerationEvent> = flow {
        if (prompt == null) return@flow
        store.appendTranscript(projectId, TranscriptEntry.Prompt(prompt, fixErrors))
        try {
            val workspace = store.workspace(projectId)
            reply(
                projectId,
                if (fixErrors) "Let me look at those errors." else "Sure, building that now."
            )
            for ((path, content) in demoSite(prompt, fixErrors)) {
                emit(GenerationEvent.ToolRunning("write_file", path))
                delay(delayMillis * 8)
                val error = (workspace.write(path, content) as? WorkspaceResult.Error)?.message
                store.appendTranscript(
                    projectId,
                    TranscriptEntry.Tool("write_file", path, error)
                )
                emit(GenerationEvent.TurnPersisted)
            }
            reply(
                projectId,
                "Done. Tap Run to try it: the button counts taps and remembers the count."
            )
            store.appendTranscript(projectId, TranscriptEntry.Usage(4_210, 1_388, 3_072))
            emit(GenerationEvent.TurnPersisted)
        } catch (e: CancellationException) {
            withContext(NonCancellable) {
                store.appendTranscript(projectId, TranscriptEntry.Notice(NoticeKind.STOPPED))
            }
            throw e
        }
    }

    private suspend fun FlowCollector<GenerationEvent>.reply(projectId: ProjectId, text: String) {
        for (word in text.split(' ')) {
            delay(delayMillis)
            emit(GenerationEvent.TextDelta("$word "))
        }
        store.appendTranscript(projectId, TranscriptEntry.Reply(text))
        emit(GenerationEvent.TurnPersisted)
    }

    private fun demoSite(prompt: String, fixErrors: Boolean): List<Pair<String, String>> {
        val title = prompt.take(60).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        val html = """
            <!doctype html>
            <html lang="en">
            <head>
              <meta charset="utf-8">
              <meta name="viewport" content="width=device-width, initial-scale=1">
              <title>$title</title>
              <link rel="stylesheet" href="css/style.css">
            </head>
            <body>
              <!-- Generated by the fake engine -->
              <h1>$title</h1>
              <button id="count">Tapped 0 times</button>
              <script type="module" src="js/app.js"></script>
            </body>
            </html>
        """.trimIndent()
        val css = """
            body { font-family: system-ui, sans-serif; margin: 0; padding: 24px; }
            button { font-size: 1.25rem; padding: 12px 20px; border-radius: 12px; }
        """.trimIndent()
        val js = """
            const button = document.getElementById("count");
            let count = Number(localStorage.getItem("count") ?? 0);
            const render = () => { button.textContent = `Tapped ${'$'}{count} times`; };
            button.addEventListener("click", () => {
              count += 1;
              localStorage.setItem("count", String(count));
              render();
            });
            render();
        """.trimIndent()
        return if (fixErrors) {
            listOf("js/app.js" to js)
        } else {
            listOf(
                "index.html" to html,
                "css/style.css" to css,
                "js/app.js" to js
            )
        }
    }
}
